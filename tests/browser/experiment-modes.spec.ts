import { expect, test } from '@playwright/test';
import type { Page } from '@playwright/test';
import { openLab, openExperiment, vectorInput, calculationStep, comparisonButton } from './open-lab.ts';
import { getLesson } from '../../web/learning/lessons.ts';

async function expectModuleBarVisible(page: Page) {
  const bar = page.locator('.learning-navigation');
  await expect(bar).toBeInViewport({ ratio: 1 });
  const barBounds = await bar.boundingBox();
  const headerBounds = await page.getByRole('banner').boundingBox();
  expect(barBounds!.y).toBeGreaterThanOrEqual(headerBounds!.y + headerBounds!.height);
}

test('one workbench preserves independent free and guided state across prediction, editing and explanation', async ({ page }) => {
  await openLab(page);
  const navigation = page.getByRole('group', { name: '学习模式' });
  await expect(navigation.getByRole('button', { name: '自由探索', exact: true })).toHaveCount(0);
  await expect(navigation.getByRole('button', { name: '引导实验', exact: true })).toHaveCount(0);
  await expect(page.locator('.help-module-card')).toHaveCount(7);
  await openExperiment(page);
  const workbench = page.locator('.lab-grid');
  const originalWorkbench = await workbench.elementHandle();
  await expect(workbench).toHaveCount(1);
  await page.getByRole('button', { name: '编辑词元 B', exact: true }).click();
  const value = (await vectorInput(page, 'B', 'V', 'y'));
  await value.fill('4');
  await (await comparisonButton(page, '保存基线')).click();
  await value.fill('3');
  await (await calculationStep(page, '3 Softmax')).click();

  const lesson = getLesson('focus');
  await openExperiment(page, 'guided');
  await expectModuleBarVisible(page);
  await page.getByRole('radio', { name: lesson.prediction.options[0]!, exact: true }).check();
  await openExperiment(page, 'free');
  await expect(value).toHaveValue('3');
  await expect(page.getByTestId('baseline-output')).toHaveText('(0.872, 1.136)');
  await expect((await calculationStep(page, '3 Softmax'))).toHaveAttribute('aria-pressed', 'true');
  await openExperiment(page, 'guided');
  await expectModuleBarVisible(page);
  await expect(page.getByRole('radio', { name: lesson.prediction.options[0]!, exact: true })).toBeChecked();
  await page.getByRole('button', { name: '记录预测，开始实验', exact: true }).click();
  const key = (await vectorInput(page, 'B', 'K', 'x'));
  await key.fill('2');
  await page.getByRole('button', { name: '给我一点提示', exact: true }).click();
  await openExperiment(page, 'free');
  await expect(value).toHaveValue('3');
  await expect(value).toBeEnabled();
  await value.fill('2.5');
  await openExperiment(page, 'guided');
  await expectModuleBarVisible(page);
  await expect(key).toHaveValue('2');
  await expect(key).toBeEnabled();
  await expect(value).toHaveValue('2');
  await expect(value).toBeDisabled();
  await expect(page.getByTestId('baseline-output')).toHaveText('(0.872, 0.568)');
  await expect(page.locator('.lesson-hint')).toBeVisible();
  await expect(page.getByRole('button', { name: '再给一点提示', exact: true })).toBeVisible();
  await expect(workbench).toHaveCount(1);
  expect(await workbench.evaluate((node, original) => node === original, originalWorkbench)).toBe(true);

  await page.getByRole('button', { name: '检查当前修改', exact: true }).click();
  await expect(key).toBeDisabled();
  const frozenOutput = await page.getByTestId('output-vector').textContent();
  const answer = page.getByRole('radio', { name: lesson.comprehension.options[1]!, exact: true });
  await answer.check();
  await openExperiment(page, 'free');
  await expect(value).toHaveValue('2.5');
  await openExperiment(page, 'guided');
  await expectModuleBarVisible(page);
  await expect(key).toBeDisabled();
  await expect(answer).toBeChecked();
  await expect(page.getByTestId('output-vector')).toHaveText(frozenOutput!);
  await page.getByRole('button', { name: '提交理解题', exact: true }).click();
  await expect(page.getByTestId('lesson-progress')).toHaveText('已完成 1 / 3');
  await navigation.getByRole('button', { name: '理解自测', exact: true }).click();
  await navigation.getByRole('button', { name: '动手实验', exact: true }).click();
  await expectModuleBarVisible(page);
  await expect(page.getByRole('group', { name: '实验方式' }).getByRole('button', { pressed: true })).toHaveText('引导任务');
  await expect(page.getByText('理解题已通过', { exact: true })).toBeVisible();
  await openExperiment(page, 'free');
  await expect(value).toHaveValue('2.5');
  await expect(page.getByTestId('baseline-output')).toHaveText('(0.872, 1.136)');
});

test('mobile modes are keyboard operable, keep the target visible, and preserve a partially edited task', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 740 });
  await openLab(page);
  await openExperiment(page);
  const modes = page.getByRole('group', { name: '实验方式' });
  await modes.getByRole('button', { name: '自由探索', exact: true }).focus();
  await page.keyboard.press('Tab');
  await expect(modes.getByRole('button', { name: '引导任务', exact: true })).toBeFocused();
  await page.keyboard.press('Enter');
  await expectModuleBarVisible(page);
  await page.getByRole('radio', { name: getLesson('focus').prediction.options[0]!, exact: true }).check();
  await page.getByRole('button', { name: '记录预测，开始实验', exact: true }).click();
  const key = (await vectorInput(page, 'B', 'K', 'x'));
  await expect(key).toBeFocused();
  const goal = page.getByRole('region', { name: '当前实验目标' });
  const inputBounds = await key.boundingBox();
  const goalBounds = await goal.boundingBox();
  expect(inputBounds!.y).toBeGreaterThanOrEqual(goalBounds!.y + goalBounds!.height);
  await key.fill('1');
  await openExperiment(page, 'free');
  await openExperiment(page, 'guided');
  await expectModuleBarVisible(page);
  await expect(key).toHaveValue('1');
  await expect(key).toBeEnabled();
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
  await page.screenshot({ path: '.tools/experiment-modes-mobile.png', fullPage: true });
});
